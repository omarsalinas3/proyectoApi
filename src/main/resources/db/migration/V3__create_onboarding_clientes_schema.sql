-- ===================================================================
-- MIGRACIÓN V3: Esquema de Onboarding de Clientes Personas Físicas
-- Cumplimiento de regla estricta: Todos los campos de texto son de tipo TEXT (sin VARCHAR).
-- ===================================================================

-- 1. TABLA PRINCIPAL: USUARIOS (CLIENTES PERSONAS FÍSICAS)
CREATE TABLE IF NOT EXISTS usuarios (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre                  TEXT NOT NULL,
    segundo_nombre          TEXT,
    apellido_paterno        TEXT NOT NULL,
    apellido_materno        TEXT NOT NULL,
    fecha_nacimiento        DATE NOT NULL,
    curp                    TEXT NOT NULL,
    rfc                     TEXT NOT NULL,
    sexo                    TEXT NOT NULL,
    nacionalidad            TEXT NOT NULL,
    estado_civil            TEXT NOT NULL,
    correo                  TEXT NOT NULL,
    telefono_movil          TEXT NOT NULL,
    telefono_alternativo    TEXT,
    ocupacion               TEXT NOT NULL,
    empresa                 TEXT NOT NULL,
    ingreso_mensual         NUMERIC(15, 2) NOT NULL,
    ine_documento_url       TEXT,
    activo                  BOOLEAN NOT NULL DEFAULT TRUE,
    fecha_registro          TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fecha_modificacion      TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_usuarios_curp UNIQUE (curp),
    CONSTRAINT uq_usuarios_rfc UNIQUE (rfc),
    CONSTRAINT uq_usuarios_correo UNIQUE (correo)
);

-- 2. TABLA RELACIONADA: DOMICILIOS
CREATE TABLE IF NOT EXISTS domicilios (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id              BIGINT NOT NULL,
    calle                   TEXT NOT NULL,
    numero_exterior         TEXT NOT NULL,
    numero_interior         TEXT,
    colonia                 TEXT NOT NULL,
    municipio               TEXT NOT NULL,
    estado                  TEXT NOT NULL,
    codigo_postal           TEXT NOT NULL,
    pais                    TEXT NOT NULL DEFAULT 'México',
    fecha_registro          TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_domicilios_usuario FOREIGN KEY (usuario_id) REFERENCES usuarios(id) ON DELETE CASCADE
);

-- 3. TABLA PRINCIPAL: CUENTA BANCARIA
CREATE TABLE IF NOT EXISTS cuenta (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id              BIGINT NOT NULL,
    numero_cuenta           TEXT NOT NULL,
    saldo_inicial           NUMERIC(15, 2) NOT NULL DEFAULT 0.00,
    saldo_disponible        NUMERIC(15, 2) NOT NULL DEFAULT 0.00,
    estatus                 TEXT NOT NULL DEFAULT 'ACTIVA',
    fecha_apertura          TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fecha_modificacion      TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_cuenta_numero_cuenta UNIQUE (numero_cuenta),
    CONSTRAINT fk_cuenta_usuario FOREIGN KEY (usuario_id) REFERENCES usuarios(id) ON DELETE RESTRICT
);

-- 4. TABLA RELACIONADA: LOGIN (AUTENTICACIÓN, BIOMETRÍA Y SESIÓN)
CREATE TABLE IF NOT EXISTS login (
    id                                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id                          BIGINT NOT NULL,
    username_cifrado                    TEXT NOT NULL,
    password_hash                       TEXT NOT NULL,
    datos_biometricos_precision         DOUBLE PRECISION,
    datos_biometricos_cifrados          TEXT,
    sesion_activa                       BOOLEAN NOT NULL DEFAULT FALSE,
    tiempo_inactividad_segundos         INTEGER NOT NULL DEFAULT 300,
    ultima_actividad                    TIMESTAMP WITH TIME ZONE,
    fecha_creacion                      TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_login_usuario UNIQUE (usuario_id),
    CONSTRAINT uq_login_username UNIQUE (username_cifrado),
    CONSTRAINT fk_login_usuario FOREIGN KEY (usuario_id) REFERENCES usuarios(id) ON DELETE CASCADE
);

-- 5. TABLA RELACIONADA: SALDOS
CREATE TABLE IF NOT EXISTS saldos (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id              BIGINT NOT NULL,
    cuenta_id               BIGINT NOT NULL,
    saldo_actual            NUMERIC(15, 2) NOT NULL DEFAULT 0.00,
    saldo_retenido          NUMERIC(15, 2) NOT NULL DEFAULT 0.00,
    saldo_disponible        NUMERIC(15, 2) NOT NULL DEFAULT 0.00,
    moneda                  TEXT NOT NULL DEFAULT 'MXN',
    fecha_actualizacion     TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_saldos_cuenta UNIQUE (cuenta_id),
    CONSTRAINT fk_saldos_usuario FOREIGN KEY (usuario_id) REFERENCES usuarios(id) ON DELETE CASCADE,
    CONSTRAINT fk_saldos_cuenta FOREIGN KEY (cuenta_id) REFERENCES cuenta(id) ON DELETE CASCADE
);

-- 6. ÍNDICES DE ALTO RENDIMIENTO PARA CONSULTAS FRECUENTES
CREATE INDEX IF NOT EXISTS idx_usuarios_curp ON usuarios(curp);
CREATE INDEX IF NOT EXISTS idx_usuarios_rfc ON usuarios(rfc);
CREATE INDEX IF NOT EXISTS idx_usuarios_correo ON usuarios(correo);
CREATE INDEX IF NOT EXISTS idx_usuarios_activo ON usuarios(activo);
CREATE INDEX IF NOT EXISTS idx_usuarios_fecha_registro ON usuarios(fecha_registro);

CREATE INDEX IF NOT EXISTS idx_domicilios_usuario ON domicilios(usuario_id);
CREATE INDEX IF NOT EXISTS idx_cuenta_usuario ON cuenta(usuario_id);
CREATE INDEX IF NOT EXISTS idx_cuenta_numero_cuenta ON cuenta(numero_cuenta);
CREATE INDEX IF NOT EXISTS idx_cuenta_estatus ON cuenta(estatus);

CREATE INDEX IF NOT EXISTS idx_login_usuario ON login(usuario_id);
CREATE INDEX IF NOT EXISTS idx_login_username ON login(username_cifrado);

CREATE INDEX IF NOT EXISTS idx_saldos_usuario ON saldos(usuario_id);
CREATE INDEX IF NOT EXISTS idx_saldos_cuenta ON saldos(cuenta_id);
