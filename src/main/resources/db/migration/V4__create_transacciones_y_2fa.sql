-- 1. SEGUNDO FACTOR DE AUTENTICACIÓN (TOTP RFC 6238) EN LA TABLA LOGIN
ALTER TABLE login ADD COLUMN IF NOT EXISTS totp_secreto_cifrado VARCHAR(255);
ALTER TABLE login ADD COLUMN IF NOT EXISTS totp_activo BOOLEAN NOT NULL DEFAULT FALSE;
-- Último intervalo de 30 s aceptado: impide reutilizar el mismo código (anti-replay)
ALTER TABLE login ADD COLUMN IF NOT EXISTS totp_ultimo_paso BIGINT;

-- 2. TRANSACCIONES ENVIADAS A GESTOPAGO
-- Guarda la petición y la respuesta de cada operación: GestoPago exige conservar esta evidencia.
CREATE TABLE IF NOT EXISTS transacciones (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id              BIGINT NOT NULL,
    cuenta_id               BIGINT NOT NULL,
    upc                     VARCHAR(15) NOT NULL,
    id_servicio             INTEGER NOT NULL,
    id_producto             BIGINT NOT NULL,
    telefono                VARCHAR(20) NOT NULL,
    referencia              VARCHAR(100),
    monto                   NUMERIC(15, 2) NOT NULL,
    hora_local              CHAR(14) NOT NULL,
    unidad                  VARCHAR(25) NOT NULL,
    estatus                 VARCHAR(25) NOT NULL,
    codigo_respuesta        VARCHAR(4),
    mensaje_respuesta       VARCHAR(600),
    id_tx_gestopago         BIGINT,
    num_autorizacion        VARCHAR(60),
    comision                NUMERIC(15, 2),
    payload_enviado         TEXT NOT NULL,
    peticion_cifrada        TEXT,
    respuesta_gestopago     TEXT,
    fecha_envio             TIMESTAMP WITH TIME ZONE,
    fecha_creacion          TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fecha_actualizacion     TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_transacciones_upc UNIQUE (upc),
    CONSTRAINT ck_transacciones_monto CHECK (monto > 0),
    CONSTRAINT ck_transacciones_estatus CHECK (estatus IN ('PENDIENTE', 'EXITOSA', 'RECHAZADA', 'PENDIENTE_CONFIRMACION')),
    CONSTRAINT fk_transacciones_usuario FOREIGN KEY (usuario_id) REFERENCES usuarios(id) ON DELETE RESTRICT,
    CONSTRAINT fk_transacciones_cuenta FOREIGN KEY (cuenta_id) REFERENCES cuenta(id) ON DELETE RESTRICT
);

CREATE INDEX IF NOT EXISTS idx_transacciones_usuario ON transacciones(usuario_id);
CREATE INDEX IF NOT EXISTS idx_transacciones_cuenta ON transacciones(cuenta_id);
CREATE INDEX IF NOT EXISTS idx_transacciones_estatus ON transacciones(estatus);
CREATE INDEX IF NOT EXISTS idx_transacciones_fecha ON transacciones(fecha_creacion);
